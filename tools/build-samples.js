// Bundles samples/*.txt into src/samples.js so the page works when opened
// straight from disk (browsers block fetch() on file://).
// Run with: node tools/build-samples.js
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'samples');
const labels = {
  'one-way-audio.txt': ['One-way audio', 'Caller can’t hear the other side'],
  'codec-488.txt': ['Codec mismatch', '488 Not Acceptable Here'],
  'auth-loop-407.txt': ['Authentication loop', 'Repeated 407'],
  'missing-ack.txt': ['Drops after 32 seconds', 'Missing ACK'],
  'rejected-404.txt': ['Call rejected', '404 Not Found']
};
const list = Object.keys(labels).filter((f) => fs.existsSync(path.join(dir, f))).map((f) => ({
  file: f, title: labels[f][0], hint: labels[f][1], text: fs.readFileSync(path.join(dir, f), 'utf8')
}));
const js = '// Generated by tools/build-samples.js - do not edit by hand.\n' +
  '(function (root) { root.SIPLens = root.SIPLens || {}; root.SIPLens.samples = ' + JSON.stringify(list, null, 1) + '; })(this);\n';
fs.writeFileSync(path.join(__dirname, '..', 'src', 'samples.js'), js);
console.log('Wrote src/samples.js with ' + list.length + ' samples');
